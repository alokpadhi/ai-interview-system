"""
Mode smoke test — validates that all three question modes
(retrieve, follow_up, clarify) are reachable and produce
correct question + feedback output.

The key design choice: responses are generated by the LLM for the ACTUAL
question retrieved, not hardcoded. Hardcoded responses are fragile because
the retrieved question is random within the topic — an overfitting response
to a confusion-matrix question will score 0 and trigger the wrong mode.

Three isolated sessions:

  Session 1 — follow_up
    LLM generates a partial, incomplete answer to the actual first question.
    Expected: score 3-6, covered non-empty, missed non-empty → follow_up.

  Session 2 — clarify  (two turns)
    Turn 1: partial answer → follow_up triggered, follow_up_count → 1.
    Turn 2: LLM generates comprehensive answer with ONE embedded misconception
            to the actual follow-up question.
    With follow_up_count=1 the condition `7.0 <= score < 8.0 and follow_ups < 1`
    is False, so clarify fires if misconceptions are detected and score >= 7.

  Session 3 — retrieve
    LLM generates a comprehensive, correct answer to the actual first question.
    Expected: score >= 8, no missed or misconceptions → retrieve.

Results are observational. Each session prints evaluation details so you can
diagnose unexpected modes.

Usage:
    python -m scripts.smoke_test_modes
"""

