# ── Main ──────────────────────────────────────────────────────────────────────

async def main():
    settings = get_settings()

    print(f"\n{'═' * 60}")
    print("  AI INTERVIEW — MODE SMOKE TEST")
    print("  Tests: retrieve  |  follow_up  |  clarify")
    print(f"{'═' * 60}")
    print(f"  Primary LLM  : {settings.ollama_model}")
    print(f"  Secondary LLM: {settings.ollama_model_secondary}")
    print(f"  Focus topic  : {FORCED_TOPIC}")

    _print_section("Infrastructure")

    complex_llm = get_complex_llm()
    fast_llm = get_fast_llm()

    vector_store = VectorStore()
    retriever = VectorRetriever(vector_store)
    initialize_concept_lookup(retriever)

    available_topics = retriever.get_available_topics()
    print(f"  ✓ Available topics ({len(available_topics)}): {available_topics}")

    cache_store = InterviewCacheStore()
    grader = DocumentGrader(llm=fast_llm)
    refiner = QueryRefiner()
    rag_service = AgenticRAGService(
        retriever=retriever,
        grader=grader,
        refiner=refiner,
        cache_store=cache_store,
    )
    agents = AgentRegistry(
        complex_llm=complex_llm,
        fast_llm=fast_llm,
        rag_service=rag_service,
        cache_store=cache_store,
        available_topics=available_topics,
        consistency_samples=settings.consistency_samples,
    )
    print("  ✓ All agents ready")

    async with AsyncSqliteSaver.from_conn_string("mode_test_checkpoints.db") as checkpointer:
        start_graph = build_start_graph(agents, default_timeout=60.0)
        interview_graph = build_interview_graph(agents, checkpointer, default_timeout=60.0)

        kwargs = dict(
            llm=complex_llm,
            agents=agents,
            start_graph=start_graph,
            interview_graph=interview_graph,
        )

        results = [
            await run_session_follow_up(**kwargs),
            await run_session_clarify(**kwargs),
            await run_session_retrieve(**kwargs),
        ]

    # ── Summary ───────────────────────────────────────────────────────────────
    print(f"\n{'═' * 60}")
    print("  MODE TEST SUMMARY")
    print(f"{'═' * 60}")

    all_passed = True
    modes_seen = set(r["actual"] for r in results)

    for r in results:
        status = "✓ PASS" if r["passed"] else "✗ FAIL"
        print(
            f"  {status}  {r['label']:<30}  "
            f"expected={r['expected']:<10}  actual={r['actual']:<10}  "
            f"score={r['eval'].get('overall_score')}"
        )
        if not r["passed"]:
            all_passed = False

    all_modes = {"retrieve", "follow_up", "clarify"}
    missing = all_modes - modes_seen
    print(f"\n  Modes observed : {sorted(modes_seen)}")
    if missing:
        print(f"  Modes missing  : {sorted(missing)}  ← possible flow bug")
    else:
        print(f"  All three modes triggered at least once.")

    print()
    if all_passed:
        print(f"  ALL THREE MODE SESSIONS PASSED ✓")
    else:
        failed = [r["label"] for r in results if not r["passed"]]
        print(f"  SESSIONS WITH UNEXPECTED MODE: {failed}")
        print(
            f"  LLM evaluation scores drive mode selection. "
            f"Check [Evaluation] and [DIAGNOSIS] output above."
        )

    print(f"{'═' * 60}\n")


if __name__ == "__main__":
    asyncio.run(main())
